// Package response provides standardized JSON response utilities and RFC 7807
// Problem Details specifications for all Ecom Ventures API endpoints.
package response

import (
	"encoding/json"
	"net/http"
	"time"
)

// SuccessEnvelope wraps successful API outputs in a predictable JSON structure.
type SuccessEnvelope struct {
	Success   bool        `json:"success"`
	Data      interface{} `json:"data,omitempty"`
	Meta      interface{} `json:"meta,omitempty"`
	Timestamp time.Time   `json:"timestamp"`
}

// ValidationErrorDetail represents a single field-level validation failure.
type ValidationErrorDetail struct {
	Field   string `json:"field"`
	Message string `json:"message"`
	Rule    string `json:"rule,omitempty"`
}

// ProblemDetails represents an RFC 7807 compliant error envelope.
type ProblemDetails struct {
	Type          string                  `json:"type"`                     // URI reference identifying the problem type
	Title         string                  `json:"title"`                    // Short, human-readable summary of problem
	Status        int                     `json:"status"`                   // HTTP status code generated by server
	Detail        string                  `json:"detail"`                   // Human-readable explanation specific to this occurrence
	Instance      string                  `json:"instance,omitempty"`       // URI reference identifying the specific occurrence
	Code          string                  `json:"code,omitempty"`           // Machine-readable internal domain error code
	InvalidParams []ValidationErrorDetail `json:"invalid_params,omitempty"` // Field validation breakdown
	Timestamp     time.Time               `json:"timestamp"`                // UTC occurrence timestamp
}

// JSON serializes the given data with the specified HTTP status code.
func JSON(w http.ResponseWriter, status int, data interface{}) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)

	envelope := SuccessEnvelope{
		Success:   status >= 200 && status < 300,
		Data:      data,
		Timestamp: time.Now().UTC(),
	}

	if err := json.NewEncoder(w).Encode(envelope); err != nil {
		http.Error(w, `{"error":"failed to serialize JSON response"}`, http.StatusInternalServerError)
	}
}

// JSONWithMeta serializes data along with pagination or contextual metadata.
func JSONWithMeta(w http.ResponseWriter, status int, data interface{}, meta interface{}) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)

	envelope := SuccessEnvelope{
		Success:   true,
		Data:      data,
		Meta:      meta,
		Timestamp: time.Now().UTC(),
	}

	if err := json.NewEncoder(w).Encode(envelope); err != nil {
		http.Error(w, `{"error":"failed to serialize JSON response"}`, http.StatusInternalServerError)
	}
}

// Problem writes an RFC 7807 error response to the client.
func Problem(w http.ResponseWriter, r *http.Request, status int, code, title, detail string) {
	w.Header().Set("Content-Type", "application/problem+json; charset=utf-8")
	w.WriteHeader(status)

	instance := ""
	if r != nil {
		instance = r.URL.Path
	}

	problem := ProblemDetails{
		Type:      "https://dropiobd.com/errors/" + code,
		Title:     title,
		Status:    status,
		Detail:    detail,
		Instance:  instance,
		Code:      code,
		Timestamp: time.Now().UTC(),
	}

	_ = json.NewEncoder(w).Encode(problem)
}

// ValidationProblem writes an RFC 7807 error response containing invalid parameter details.
func ValidationProblem(w http.ResponseWriter, r *http.Request, invalidParams []ValidationErrorDetail) {
	w.Header().Set("Content-Type", "application/problem+json; charset=utf-8")
	w.WriteHeader(http.StatusUnprocessableEntity)

	instance := ""
	if r != nil {
		instance = r.URL.Path
	}

	problem := ProblemDetails{
		Type:          "https://dropiobd.com/errors/VALIDATION_FAILED",
		Title:         "Validation Failed",
		Status:        http.StatusUnprocessableEntity,
		Detail:        "One or more parameters failed validation constraints.",
		Instance:      instance,
		Code:          "VALIDATION_FAILED",
		InvalidParams: invalidParams,
		Timestamp:     time.Now().UTC(),
	}

	_ = json.NewEncoder(w).Encode(problem)
}

// Convenience error helper functions
func BadRequest(w http.ResponseWriter, r *http.Request, detail string) {
	Problem(w, r, http.StatusBadRequest, "BAD_REQUEST", "Bad Request", detail)
}

func Unauthorized(w http.ResponseWriter, r *http.Request, detail string) {
	Problem(w, r, http.StatusUnauthorized, "UNAUTHORIZED", "Unauthorized Access", detail)
}

func Forbidden(w http.ResponseWriter, r *http.Request, detail string) {
	Problem(w, r, http.StatusForbidden, "FORBIDDEN", "Forbidden Operation", detail)
}

func NotFound(w http.ResponseWriter, r *http.Request, detail string) {
	Problem(w, r, http.StatusNotFound, "NOT_FOUND", "Resource Not Found", detail)
}

func InternalServerError(w http.ResponseWriter, r *http.Request) {
	Problem(w, r, http.StatusInternalServerError, "INTERNAL_SERVER_ERROR", "Internal Server Error", "An unexpected error occurred. Please contact system support.")
}

// WriteProblem provides backward compatibility with callers expecting the Phase 1 signature.
func WriteProblem(w http.ResponseWriter, r *http.Request, status int, title, detail string) {
	code := http.StatusText(status)
	if code == "" {
		code = "ERROR"
	}
	Problem(w, r, status, code, title, detail)
}

// WriteJSON serializes the given data with the specified HTTP status code.
func WriteJSON(w http.ResponseWriter, status int, data interface{}) {
	JSON(w, status, data)
}

// WriteBadRequest writes a bad request problem response.
func WriteBadRequest(w http.ResponseWriter, r *http.Request, detail string) {
	BadRequest(w, r, detail)
}

// WriteNotFound writes a not found problem response.
func WriteNotFound(w http.ResponseWriter, r *http.Request, detail string) {
	NotFound(w, r, detail)
}

// WriteUnauthorized writes an unauthorized problem response.
func WriteUnauthorized(w http.ResponseWriter, r *http.Request, detail string) {
	Unauthorized(w, r, detail)
}

// WriteForbidden writes a forbidden problem response.
func WriteForbidden(w http.ResponseWriter, r *http.Request, detail string) {
	Forbidden(w, r, detail)
}

// Conflict writes a conflict problem response (409 Conflict).
func Conflict(w http.ResponseWriter, r *http.Request, detail string) {
	Problem(w, r, http.StatusConflict, "CONFLICT", "Conflict", detail)
}

// WriteConflict writes a conflict problem response.
func WriteConflict(w http.ResponseWriter, r *http.Request, detail string) {
	Conflict(w, r, detail)
}

// WriteInternalError writes an internal server error problem response.
func WriteInternalError(w http.ResponseWriter, r *http.Request, detail string) {
	Problem(w, r, http.StatusInternalServerError, "INTERNAL_SERVER_ERROR", "Internal Server Error", detail)
}

// WriteNoContent writes a 204 No Content response.
func WriteNoContent(w http.ResponseWriter) {
	w.WriteHeader(http.StatusNoContent)
}

// InvalidParam represents a single invalid parameter for WriteValidationError.
type InvalidParam struct {
	Name   string `json:"name"`
	Reason string `json:"reason"`
}

// WriteValidationError writes validation error problem details.
func WriteValidationError(w http.ResponseWriter, r *http.Request, params []InvalidParam) {
	details := make([]ValidationErrorDetail, len(params))
	for i, p := range params {
		details[i] = ValidationErrorDetail{
			Field:   p.Name,
			Message: p.Reason,
		}
	}
	ValidationProblem(w, r, details)
}
